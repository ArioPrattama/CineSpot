USE cinespot;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS Transaction_FnB_Item;
DROP TABLE IF EXISTS Transaction_Seat;
DROP TABLE IF EXISTS Review;
DROP TABLE IF EXISTS Transaction;
DROP TABLE IF EXISTS Promo;
DROP TABLE IF EXISTS Seat;
DROP TABLE IF EXISTS Schedule;
DROP TABLE IF EXISTS Movie;
DROP TABLE IF EXISTS Studio;
DROP TABLE IF EXISTS Cinema;
DROP TABLE IF EXISTS FnB_Item;
DROP TABLE IF EXISTS User;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE User(

UserID INT AUTO_INCREMENT PRIMARY KEY,

fullName VARCHAR(100) NOT NULL,

email VARCHAR(100) NOT NULL UNIQUE,

password VARCHAR(255) NOT NULL,

phone VARCHAR(20),

loyaltyPoints INT DEFAULT 0,

role ENUM('admin','user') DEFAULT 'user',

created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

last_login DATETIME NULL

);

CREATE TABLE Cinema(

CinemaID INT AUTO_INCREMENT PRIMARY KEY,

name VARCHAR(100) NOT NULL,

city VARCHAR(100),

address TEXT,

created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP

);

CREATE TABLE Studio(

StudioID INT AUTO_INCREMENT PRIMARY KEY,

CinemaID INT NOT NULL,

name VARCHAR(50),

type ENUM('Regular','IMAX','Dolby'),

capacity INT,

created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

FOREIGN KEY(CinemaID)

REFERENCES Cinema(CinemaID)

ON UPDATE CASCADE

ON DELETE CASCADE

);

CREATE TABLE Movie(

MovieID INT AUTO_INCREMENT PRIMARY KEY,

title VARCHAR(150),

synopsis TEXT,

duration INT,

poster VARCHAR(255),

rating VARCHAR(10),

genre VARCHAR(100),

releaseDate DATE,

status ENUM('Now Showing','Coming Soon'),

created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP

);

CREATE TABLE Schedule(

ScheduleID INT AUTO_INCREMENT PRIMARY KEY,

MovieID INT NOT NULL,

StudioID INT NOT NULL,

showTime DATETIME NOT NULL,

ticketPrice DECIMAL(10,2) NOT NULL,

availableSeat INT,

created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

FOREIGN KEY(MovieID)
REFERENCES Movie(MovieID)
ON UPDATE CASCADE
ON DELETE CASCADE,

FOREIGN KEY(StudioID)
REFERENCES Studio(StudioID)
ON UPDATE CASCADE
ON DELETE CASCADE

);

CREATE TABLE Seat(

SeatID INT AUTO_INCREMENT PRIMARY KEY,

StudioID INT NOT NULL,

seatRow CHAR(1) NOT NULL,

seatNumber INT NOT NULL,

status ENUM('Available','Booked') DEFAULT 'Available',

created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

UNIQUE(StudioID,seatRow,seatNumber),

FOREIGN KEY(StudioID)
REFERENCES Studio(StudioID)
ON UPDATE CASCADE
ON DELETE CASCADE

);

CREATE TABLE Promo(

PromoID INT AUTO_INCREMENT PRIMARY KEY,

promoCode VARCHAR(50) UNIQUE,

discount DECIMAL(5,2),

validity DATE,

minimumPurchase DECIMAL(10,2),

status ENUM('Active','Inactive') DEFAULT 'Active',

created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP

);

CREATE TABLE `Transaction`(

TransactionID INT AUTO_INCREMENT PRIMARY KEY,

UserID INT NOT NULL,

ScheduleID INT NOT NULL,

PromoID INT NULL,

qris VARCHAR(255),

totalAmount DECIMAL(10,2),

paymentMethod ENUM('QRIS','Cash','Debit','Credit'),

paymentStatus ENUM('Pending','Paid','Cancelled') DEFAULT 'Pending',

createdDate DATETIME DEFAULT CURRENT_TIMESTAMP,

updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

INDEX(UserID),
INDEX(ScheduleID),

FOREIGN KEY(UserID)
REFERENCES `User`(UserID)
ON UPDATE CASCADE
ON DELETE CASCADE,

FOREIGN KEY(ScheduleID)
REFERENCES Schedule(ScheduleID)
ON UPDATE CASCADE
ON DELETE CASCADE,

FOREIGN KEY(PromoID)
REFERENCES Promo(PromoID)
ON UPDATE CASCADE
ON DELETE SET NULL

);

CREATE TABLE Review(

ReviewID INT AUTO_INCREMENT PRIMARY KEY,

MovieID INT NOT NULL,

UserID INT NOT NULL,

ratingScore INT,

comment TEXT,

created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

FOREIGN KEY(MovieID)
REFERENCES Movie(MovieID)
ON UPDATE CASCADE
ON DELETE CASCADE,

FOREIGN KEY(UserID)
REFERENCES `User`(UserID)
ON UPDATE CASCADE
ON DELETE CASCADE

);

CREATE TABLE FnB_Item(

FnBID INT AUTO_INCREMENT PRIMARY KEY,

name VARCHAR(100),

category VARCHAR(50),

price DECIMAL(10,2),

image VARCHAR(255),

stock INT DEFAULT 0,

status ENUM('Available','Unavailable') DEFAULT 'Available',

created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP

);

CREATE TABLE Transaction_Seat(

TransactionID INT,

SeatID INT,

PRIMARY KEY(TransactionID,SeatID),

FOREIGN KEY(TransactionID)
REFERENCES `Transaction`(TransactionID)
ON UPDATE CASCADE
ON DELETE CASCADE,

FOREIGN KEY(SeatID)
REFERENCES Seat(SeatID)
ON UPDATE CASCADE
ON DELETE CASCADE

);

CREATE TABLE Transaction_FnB_Item(

TransactionFnBItemID INT AUTO_INCREMENT PRIMARY KEY,

TransactionID INT NOT NULL,

FnBID INT NOT NULL,

quantity INT,

subtotal DECIMAL(10,2),

FOREIGN KEY(TransactionID)
REFERENCES `Transaction`(TransactionID)
ON UPDATE CASCADE
ON DELETE CASCADE,

FOREIGN KEY(FnBID)
REFERENCES FnB_Item(FnBID)
ON UPDATE CASCADE
ON DELETE CASCADE

);

